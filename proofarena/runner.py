"""Isolated verification runner (PA-010).

Controls implemented here, and the limits of each:

* **No outbound network** — a generated ``sitecustomize.py`` replaces socket
  entry points with a deny stub and prints ``SANDBOX_BLOCKED_NETWORK``. This is
  in-process Python-level denial, not a kernel namespace.
* **No host secrets** — the child gets an explicit environment allowlist. The
  session secret, wallet key and database paths are never forwarded.
* **No host working tree** — sources are copied into a throwaway sandbox
  directory; the child works only there.
* **Bounded time and output** — wall-clock timeout with process-tree kill, and
  captured output is capped (RUN-003/RUN-007).

Not implemented (declared, not faked): OCI/container isolation, memory cgroup
limits, PID limits, read-only base filesystem. Those need Docker, which is not
available in this environment — see docs/adr/0002-runner-isolation.md.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import time
import uuid
from dataclasses import asdict, dataclass, field
from pathlib import Path

from .canonical import sha256_text
from .config import RUNNER_MAX_OUTPUT_BYTES, RUNNER_TIMEOUT_S

INVARIANT_MARKER = "PROOFARENA-INVARIANT:ALLOWANCE_EXCEEDED"
NETWORK_BLOCK_MARKER = "SANDBOX_BLOCKED_NETWORK"

SANDBOX_SITECUSTOMIZE = '''\
"""Generated by ProofArena runner: deny outbound network and record attempts.

Only *egress* entry points are replaced. ``socket.socket`` itself stays the real
class because ``ssl`` subclasses it at import time; replacing the class breaks
the interpreter before any test runs (that failure mode is itself a lesson).
"""

import os
import sys

if os.environ.get("PROOFARENA_SANDBOX") == "1":  # pragma: no cover - child process
    try:
        import socket

        _NETLOG = os.environ.get("PROOFARENA_SANDBOX_NETLOG")

        def _record():
            # A file, not stdout: pytest captures stderr per-test, so a marker
            # printed to stdout would vanish when the attack test passes.
            if _NETLOG:
                try:
                    with open(_NETLOG, "a", encoding="utf-8") as handle:
                        handle.write("blocked\\n")
                except OSError:
                    pass

        def _deny(*_args, **_kwargs):
            _record()
            sys.stderr.write("SANDBOX_BLOCKED_NETWORK\\n")
            sys.stderr.flush()
            raise OSError("network access denied by the ProofArena sandbox")

        socket.create_connection = _deny
        socket.getaddrinfo = _deny
        socket.gethostbyname = _deny

        def _deny_connect(self, *_args, **_kwargs):
            _deny()

        try:
            socket.socket.connect = _deny_connect
            socket.socket.connect_ex = _deny_connect
        except Exception:
            pass
    except Exception as exc:  # never let the guard break collection
        sys.stderr.write(f"SANDBOX_GUARD_ERROR {exc!r}\\n")
'''

SANDBOX_CONFTEST = '''\
"""Generated by ProofArena runner: make the sandbox root importable."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
'''

#: Environment variables the child is allowed to see. Everything else is dropped.
ENV_ALLOWLIST = (
    "PATH",
    "SYSTEMROOT",
    "SYSTEMDRIVE",
    "WINDIR",
    "COMSPEC",
    "PATHEXT",
    "NUMBER_OF_PROCESSORS",
    "PROCESSOR_ARCHITECTURE",
)

FORBIDDEN_ENV_HINTS = (
    "SECRET",
    "PRIVATE",
    "SEED",
    "MNEMONIC",
    "KEY",
    "TOKEN",
    "PASSWORD",
    "WALLET",
    "NEAR",
    "RPC",
)


@dataclass
class RunResult:
    label: str
    command: list[str]
    exit_code: int
    elapsed_s: float
    timed_out: bool
    stdout: str
    stdout_sha256: str
    truncated: bool
    invariant_failed: bool
    invariant_marker_seen: bool
    network_block_events: int
    sandbox_dir: str

    def to_public(self) -> dict[str, object]:
        return {
            "label": self.label,
            "command": " ".join(self.command),
            "exit_code": self.exit_code,
            "invariant_failed": self.invariant_failed,
            "output_sha256": self.stdout_sha256,
            "timed_out": self.timed_out,
            "elapsed_s": round(self.elapsed_s, 3),
            "truncated": self.truncated,
            "network_block_events": self.network_block_events,
        }


@dataclass
class SandboxSpec:
    baseline_dir: Path
    patched_dir: Path
    tests_dir: Path
    work_root: Path


def _copy_tree_contents(source: Path, target: Path) -> list[str]:
    target.mkdir(parents=True, exist_ok=True)
    copied: list[str] = []
    for item in sorted(source.iterdir()):
        if item.name in {"__pycache__", ".pytest_cache"}:
            continue
        if item.is_dir():
            for child in item.rglob("*"):
                if child.is_file() and "__pycache__" not in child.parts:
                    rel = child.relative_to(source)
                    dest = target / rel
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copyfile(child, dest)
                    copied.append(str(rel))
        elif item.is_file():
            shutil.copyfile(item, target / item.name)
            copied.append(item.name)
    return copied


def materialize(spec: SandboxSpec, variant: str, label: str) -> Path:
    """Create a fresh sandbox containing exactly one fixture variant + tests."""
    sandbox = spec.work_root / f"sbx-{variant}-{label}-{uuid.uuid4().hex[:8]}"
    sandbox.mkdir(parents=True, exist_ok=False)
    source = spec.baseline_dir if variant == "baseline" else spec.patched_dir
    copied = _copy_tree_contents(source, sandbox)
    copied += _copy_tree_contents(spec.tests_dir, sandbox / "tests")
    (sandbox / "conftest.py").write_text(SANDBOX_CONFTEST, encoding="utf-8")
    (sandbox / "sitecustomize.py").write_text(SANDBOX_SITECUSTOMIZE, encoding="utf-8")
    (sandbox / ".tmp").mkdir(exist_ok=True)
    (sandbox / "COPIED_FILES.txt").write_text("\n".join(sorted(copied)) + "\n", encoding="utf-8")
    return sandbox


def _child_env(sandbox: Path) -> dict[str, str]:
    env = {"PROOFARENA_SANDBOX": "1", "PYTHONIOENCODING": "utf-8", "PYTHONDONTWRITEBYTECODE": "1"}
    for key in ENV_ALLOWLIST:
        value = os.environ.get(key)
        if value:
            env[key] = value

    # Only the sandbox root is prepended. Adding site-packages here would shadow
    # stdlib modules (this interpreter has an old ``pathlib`` wheel installed).
    env["PYTHONPATH"] = str(sandbox)

    # HOME/USERPROFILE are *not* overridden, and APPDATA is not forwarded, so the
    # user site directory is pinned explicitly instead. Without this the child
    # cannot import pytest plugins installed in the user site.
    try:
        import site as _site

        env["PYTHONUSERBASE"] = _site.getuserbase()
    except Exception:  # pragma: no cover - defensive
        pass

    env["TEMP"] = str(sandbox / ".tmp")
    env["TMP"] = str(sandbox / ".tmp")
    env["PROOFARENA_SANDBOX_NETLOG"] = str(sandbox / "network-blocked.log")
    for key in list(env):
        if any(hint in key.upper() for hint in FORBIDDEN_ENV_HINTS):
            env.pop(key, None)
    return env


def _kill_tree(pid: int) -> None:
    if os.name == "nt":
        subprocess.run(
            ["taskkill", "/F", "/T", "/PID", str(pid)],
            capture_output=True,
            check=False,
        )
    else:  # pragma: no cover - POSIX fallback
        try:
            os.killpg(pid, 9)
        except OSError:
            pass


def run_pytest(
    sandbox: Path,
    *,
    target: str,
    label: str,
    timeout_s: int = RUNNER_TIMEOUT_S,
    max_output_bytes: int = RUNNER_MAX_OUTPUT_BYTES,
    extra_args: list[str] | None = None,
) -> RunResult:
    command = [
        sys.executable,
        "-B",
        "-m",
        "pytest",
        "-q",
        "-p",
        "no:cacheprovider",
        # This host has a third-party pytest plugin (web3's pytest_ethereum) that
        # fails to import; the pinned sandbox command must not depend on host
        # plugin autoload.
        "-p",
        "no:pytest_ethereum",
        "--no-header",
        *(extra_args or []),
        target,
    ]
    started = time.monotonic()
    proc = subprocess.Popen(
        command,
        cwd=str(sandbox),
        env=_child_env(sandbox),
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        encoding="utf-8",
        errors="replace",
        creationflags=subprocess.CREATE_NEW_PROCESS_GROUP if os.name == "nt" else 0,
    )
    timed_out = False
    try:
        raw, _ = proc.communicate(timeout=timeout_s)
        exit_code = proc.returncode
    except subprocess.TimeoutExpired:
        timed_out = True
        _kill_tree(proc.pid)
        try:
            raw, _ = proc.communicate(timeout=15)
        except subprocess.TimeoutExpired:  # pragma: no cover - stubborn child
            proc.kill()
            raw = ""
        exit_code = -1
    elapsed = time.monotonic() - started

    netlog = sandbox / "network-blocked.log"
    file_block_events = 0
    if netlog.exists():
        file_block_events = sum(1 for line in netlog.read_text(encoding="utf-8", errors="replace").splitlines() if line.strip() == "blocked")

    text = raw or ""
    truncated = len(text.encode("utf-8", errors="replace")) > max_output_bytes
    if truncated:
        text = text.encode("utf-8", errors="replace")[:max_output_bytes].decode("utf-8", errors="replace")

    return RunResult(
        label=label,
        command=command,
        exit_code=exit_code,
        elapsed_s=elapsed,
        timed_out=timed_out,
        stdout=text,
        stdout_sha256=sha256_text(text),
        truncated=truncated,
        invariant_failed=(not timed_out and exit_code != 0 and INVARIANT_MARKER in text),
        invariant_marker_seen=INVARIANT_MARKER in text,
        network_block_events=max(file_block_events, text.count(NETWORK_BLOCK_MARKER)),
        sandbox_dir=str(sandbox),
    )


@dataclass
class SandboxReport:
    """Everything the runner observed, before any interpretation."""

    runs: list[RunResult] = field(default_factory=list)
    copied_files: list[str] = field(default_factory=list)
    prompt_injection_samples: list[str] = field(default_factory=list)

    def to_public(self) -> dict[str, object]:
        return {
            "runs": [r.to_public() for r in self.runs],
            "copied_files": self.copied_files,
            "prompt_injection_samples": self.prompt_injection_samples,
        }


def scan_for_injection(directory: Path) -> list[str]:
    """Record (never obey) instruction-like lines found in untrusted fixture text."""
    samples: list[str] = []
    for path in sorted(directory.rglob("*")):
        if not path.is_file() or path.suffix.lower() not in {".md", ".txt", ".rst", ".py"}:
            continue
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for line in text.splitlines():
            cleaned = line.strip()
            if cleaned.upper().startswith(("SYSTEM:", "IGNORE PREVIOUS", "IGNORE PRIOR")):
                samples.append(f"{path.name}: {cleaned[:200]}")
    return samples


def run_result_dict(result: RunResult) -> dict[str, object]:
    return asdict(result)
